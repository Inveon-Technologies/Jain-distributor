/**
 * Turns the shop's item export (name <TAB> packing per line) into the seed migration:
 *
 *   npx tsx scripts/item-master-sql.ts items.tsv > migrations/003_item_master_seed.sql
 *
 * Uses the same cleaning rules as the admin "Import items" button (src/modules/items/importer.ts).
 */
import { readFileSync } from "node:fs";
import { parseItemList } from "../src/modules/items/importer.js";

const file = process.argv[2];
if (!file) {
  console.error("Usage: tsx scripts/item-master-sql.ts <items.tsv>");
  process.exit(1);
}
const { items, skipped } = parseItemList(readFileSync(file, "utf8"));
const q = (v: string | number | null) => (v === null ? "NULL" : typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);

const out: string[] = [
  "-- Item Master seed: the distributor's item list (generated by scripts/item-master-sql.ts).",
  `-- ${items.length} items; ${skipped.length} lines skipped (header, blank names, exact duplicates, non-items).`,
  "-- Re-running is safe: existing name + packing pairs are left alone.",
  "",
];
const CHUNK = 500;
for (let i = 0; i < items.length; i += CHUNK) {
  out.push("INSERT INTO items (name, unit, pack_type, pack_qty, free_qty, price) VALUES");
  const rows = items.slice(i, i + CHUNK).map(
    (it) => `  (${[it.name, it.unit, it.packType, it.packQty, it.freeQty, it.price].map(q).join(", ")})`,
  );
  out.push(rows.join(",\n"));
  out.push("ON CONFLICT (lower(name), lower(unit)) WHERE deleted_at IS NULL DO NOTHING;", "");
}
process.stdout.write(out.join("\n"));
for (const s of skipped) console.error(`skipped line ${s.line}: ${s.reason}: ${s.text}`);
